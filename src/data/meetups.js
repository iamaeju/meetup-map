export function buildChatThreads(meetups, currentUser) {
  return meetups
    .filter((m) => m.participants.includes(currentUser))
    .map((m) => ({
      id: m.id,
      meetupId: m.id,
      title: m.title,
      avatar: m.hostAvatar || '💬',
      hostName: m.hostName,
      lastMessage: `${m.hostName}: 모임 전 꼭 확인해주세요! 장소는 ${m.address} 입니다.`,
      time: '방금',
      unread: 0,
    }));
}
